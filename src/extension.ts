/**
 * GitHub CLI extension packaging.
 *
 * `gh extension install` requires the *repository* name to start with `gh-`,
 * which this package's does not. Rather than rename the package, stacklore
 * installs itself: it writes a small shim into gh's extension directory that
 * execs this CLI. That works for every install route — global npm, npx, or a
 * source checkout — because the shim records absolute paths at install time.
 */

import { chmod, mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import { homedir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

/** Extension name, and therefore the `gh <name>` subcommand. */
export const EXTENSION_NAME = "gh-stacklore";

/**
 * gh stores extensions under its data directory, honouring `XDG_DATA_HOME`
 * on Linux and macOS alike.
 */
export function extensionDir(env: NodeJS.ProcessEnv = process.env): string {
  const base = env["XDG_DATA_HOME"] || join(homedir(), ".local", "share");
  return join(base, "gh", "extensions", EXTENSION_NAME);
}

/** Absolute path to this CLI's entry point, as shipped. */
export function cliPath(): string {
  return fileURLToPath(new URL("cli.js", import.meta.url));
}

/**
 * The shim is bash rather than a symlink to `cli.js` because gh executes the
 * file directly: a `.js` file has no interpreter of its own, and relying on its
 * shebang would break whenever a different node is first on `PATH`. Paths are
 * JSON-quoted so spaces in a home directory cannot split the command.
 */
export function shimScript(node: string, cli: string): string {
  return `#!/usr/bin/env bash
# Generated by 'stacklore gh-install'. Re-run that command to update paths.
exec ${JSON.stringify(node)} ${JSON.stringify(cli)} "$@"
`;
}

export interface ExtensionOptions {
  env?: NodeJS.ProcessEnv;
  /** Node binary the shim should exec. Defaults to the running one. */
  node?: string;
  /** CLI entry point the shim should run. Defaults to this package's. */
  cli?: string;
}

export interface InstallResult {
  path: string;
  /** False when an identical shim was already in place. */
  changed: boolean;
}

/** Install, or refresh, the `gh stacklore` extension for the current user. */
export async function installExtension(
  options: ExtensionOptions = {},
): Promise<InstallResult> {
  const dir = extensionDir(options.env ?? process.env);
  const target = join(dir, EXTENSION_NAME);
  const script = shimScript(
    options.node ?? process.execPath,
    options.cli ?? cliPath(),
  );

  // Rewriting an identical shim would be harmless, but reporting it as a change
  // misleads anyone checking whether their install is current.
  const existing = existsSync(target)
    ? await readFile(target, "utf8").catch(() => null)
    : null;
  if (existing === script) return { path: target, changed: false };

  await mkdir(dir, { recursive: true });
  await writeFile(target, script, "utf8");
  await chmod(target, 0o755);
  return { path: target, changed: true };
}

/** Remove the extension. Returns false when it was not installed. */
export async function uninstallExtension(
  options: ExtensionOptions = {},
): Promise<boolean> {
  const dir = extensionDir(options.env ?? process.env);
  if (!existsSync(dir)) return false;
  await rm(dir, { recursive: true, force: true });
  return true;
}

/** Whether the extension is currently installed, for `status`. */
export function extensionInstalled(
  env: NodeJS.ProcessEnv = process.env,
): boolean {
  return existsSync(join(extensionDir(env), EXTENSION_NAME));
}
